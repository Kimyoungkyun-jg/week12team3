std::string GenerateHeader(const FHeaderInfo& Header, const std::string& ModuleName)
{
    const std::string Guard = MakeGuardName(ModuleName, Header.GeneratedName);

    std::string Out;
    Out += "// Generated by HitoriHeaderTool. Do not edit; edit " + Header.RelativePath + " instead.\n";
    Out += "\n";
    Out += "#ifdef " + Guard + "\n";
    Out += "#error \"" + Header.GeneratedName + " included twice. Check that the source header has #pragma once.\"\n";
    Out += "#endif\n";
    Out += "#define " + Guard + "\n";
    Out += "\n";
    // enum만 있는 헤더는 가벼운 Enum.h만 include한다. Class.h는 Object.h까지 끌고 와서 순환 include가 생기기 쉽다.
    Out += Header.Classes.empty() ? "#include \"UObject/Enum.h\"\n" : "#include \"UObject/Class.h\"\n";
    Out += "\n";

    for (const FEnumInfo& Enum : Header.Enums)
    {
        Out += "// " + Enum.Name + " (" + std::to_string(Enum.Entries.size()) + " entries)\n";
        Out += "enum class " + Enum.Name + (Enum.UnderlyingType.empty() ? "" : " : " + Enum.UnderlyingType) + ";\n";
        Out += "template <>\n";
        Out += "struct TEnumInfo<" + Enum.Name + ">\n";
        Out += "{\n";
        Out += "\tstatic constexpr bool bReflected = true;\n";
        Out += "\n";
        Out += "\t// This file is included before the enum definition, so " + Enum.Name + "::Entry cannot be named yet.\n";
        Out += "\t// As a template, it is instantiated at first use (after the enum definition).\n";
        Out += "\ttemplate <typename E = " + Enum.Name + ">\n";
        Out += "\tstatic const FEnumInfo* Get()\n";
        Out += "\t{\n";
        Out += "\t\tstatic const FEnumInfo Info{ \"" + Enum.Name + "\", {\n";
        for (const FEnumEntryInfo& Entry : Enum.Entries)
        {
            Out += "\t\t\t{ \"" + Entry.Name + "\", static_cast<int64>(E::" + Entry.Name + "), " + (Entry.bHidden ? "true" : "false") + " },\n";
        }
        Out += "\t\t} };\n";
        Out += "\t\treturn &Info;\n";
        Out += "\t}\n";
        Out += "};\n";
        Out += "\n";
    }

    for (const FClassInfo& Class : Header.Classes)
    {
        std::vector<std::string> Lines;
        if (Class.bIsStruct)
        {
            // USTRUCT: StaticStruct()가 RegisterProperties를 항상 부르므로 프로퍼티가 없어도 만든다.
            // 구조체 멤버의 기본 접근은 public이라 DECLARE_STRUCT가 public:으로 끝난다 (UCLASS는 private:).
            Lines.push_back("\tDECLARE_STRUCT(" + Class.Name + ", " + (Class.SuperName.empty() ? std::string("void") : Class.SuperName) + ")");
            AddRegisterProperties(Lines, Class, "UScriptStruct", "InStruct");
        }
        else
        {
            Lines.push_back("\tDECLARE_CLASS(" + Class.Name + ", " + Class.SuperName + ")");
            if (!Class.Properties.empty())
            {
                AddRegisterProperties(Lines, Class, "UClass", "InClass");
                Lines.push_back("private:");
            }
        }

        if (!Class.Functions.empty())
        {
            // 시그니처는 &ThisClass::이름 에서 TNativeFunction이 알아낸다 (Runtime/UObject/Function.h).
            Lines.push_back("public:");
            Lines.push_back("\tstatic void RegisterFunctions(UClass* InClass)");
            Lines.push_back("\t{");
            for (const FFunctionInfo& Function : Class.Functions)
            {
                Lines.push_back("\t\tInClass->AddFunction<&ThisClass::" + Function.Name + ">(\"" + Function.Name + "\", "
                    + (Function.Flags.empty() ? std::string("FUNC_None") : JoinFlags(Function.Flags)) + ");");
            }
            Lines.push_back("\t}");
            Lines.push_back("private:");
        }

        // GENERATED_BODY()가 이 이름으로 바뀐다: CURRENT_FILE_ID _ __LINE__ _GENERATED_BODY
        const std::string MacroName = Header.FileId + "_" + std::to_string(Class.GeneratedBodyLine) + "_GENERATED_BODY";
		Out += "// " + Class.Name + (Class.bIsStruct ? " (USTRUCT, " : " (") + std::to_string(Class.Properties.size()) + " properties, "
            + std::to_string(Class.Functions.size()) + " functions)\n";
        Out += MakeMacro(MacroName, Lines);
        Out += "\n";
    }

    // CURRENT_FILE_ID는 GENERATED_BODY()만 쓴다. enum만 있는 헤더는 건드리지 않는다.
    if (!Header.Classes.empty())
    {
        Out += "#undef CURRENT_FILE_ID\n";
        Out += "#define CURRENT_FILE_ID " + Header.FileId + "\n";
    }
    return Out;
}

bool ReadTextFile(const fs::path& Path, std::string& OutText)
{
    std::ifstream Stream(Path, std::ios::binary);
    if (!Stream)
    {
        return false;
    }
    std::ostringstream Buffer;
    Buffer << Stream.rdbuf();
    OutText = Buffer.str();
    return true;
}

bool WriteIfChanged(const fs::path& Path, const std::string& Content, bool& bOutWritten, FDiagnostics& Diag)
{
    bOutWritten = false;

    std::string Existing;
    if (ReadTextFile(Path, Existing) && Existing == Content)
    {
        return true;
    }

    std::ofstream Stream(Path, std::ios::binary | std::ios::trunc);
    Stream.write(Content.data(), (std::streamsize)Content.size());
    if (!Stream)
    {
        Diag.Error(Path, 1, "Failed to write the generated file.");
        return false;
    }
    bOutWritten = true;
    return true;
}